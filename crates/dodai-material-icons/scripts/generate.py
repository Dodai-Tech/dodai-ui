#!/usr/bin/env python3
"""Regenerate src/{outlined,rounded,sharp}.rs from the official Material Symbols
SVGs (npm `@material-symbols/svg-400`, Apache-2.0, weight 400, 24px optical size).

    npm pack @material-symbols/svg-400 && tar xzf material-symbols-svg-400-*.tgz
    python3 scripts/generate.py package

Each icon is stored as its SVG path data only (viewBox `0 -960 960 960`),
sorted by name so lookups can binary-search.
"""
import os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else "package"
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src")
pat = re.compile(r'<path d="([^"]*)"')
for style in ("outlined", "rounded", "sharp"):
    d = os.path.join(src, style)
    rows = []
    for f in sorted(os.listdir(d)):
        if not f.endswith(".svg"):
            continue
        paths = pat.findall(open(os.path.join(d, f)).read())
        assert paths, f
        rows.append((f[:-4], "".join(paths)))
    rows.sort()
    with open(os.path.join(out, f"{style}.rs"), "w") as o:
        o.write("// @generated by scripts/generate.py from Material Symbols (Apache-2.0). Do not edit.\n")
        o.write("use crate::Icon;\n\n")
        o.write(f"/// All {len(rows)} {style} icons (including `-fill` variants), sorted by name.\n")
        o.write("pub static ALL: &[Icon] = &[\n")
        for n, p in rows:
            o.write(f'    Icon {{ name: "{n}", path: "{p}" }},\n')
        o.write("];\n")
    print(style, len(rows))
