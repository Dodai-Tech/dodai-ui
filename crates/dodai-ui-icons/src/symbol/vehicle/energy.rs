//! Battery, charging and emissions.

use super::*;

/// A horizontal battery with `n` of four cells lit.
fn cells(n: usize) -> Vec<Shape> {
    let mut v = vec![
        rrect(2.5, 7.0, 19.5, 17.0, 1.5),
        line(&[(19.5, 10.0), (21.5, 10.0), (21.5, 14.0), (19.5, 14.0)]),
    ];
    v.extend((0..n).map(|i| {
        let x = 4.8 + i as f32 * 3.6;
        rrect(x, 9.3, x + 2.2, 14.7, 0.4)
    }));
    v
}

pub(super) fn shapes(i: Symbol) -> Vec<Shape> {
    use Symbol::*;
    match i {
        BatteryEmpty => {
            let mut v = cells(0);
            v.push(line(&[(11.0, 9.5), (11.0, 12.5)]));
            v.push(dot(11.0, 14.6));
            v
        }
        BatteryQuarter => cells(1),
        BatteryHalf => cells(2),
        BatteryThreeQuarters => cells(3),
        BatteryFull => cells(4),
        BatteryEmptyFuel => vec![
            rrect(2.5, 4.0, 14.5, 11.0, 1.2),
            line(&[(14.5, 6.0), (16.0, 6.0), (16.0, 9.0), (14.5, 9.0)]),
            drop(16.0, 17.5, 3.3),
            line(&[(4.0, 15.0), (9.5, 15.0)]),
            line(&[(4.0, 18.5), (9.5, 18.5)]),
        ],
        Charging => vec![
            arc(12.0, 12.0, 9.0, -60.0, 240.0),
            head(7.5, 4.2, 330.0, 2.2),
            bolt(12.0, 12.0, 9.0),
        ],
        ChargeLevel => vec![
            rrect(7.0, 4.5, 17.0, 21.0, 1.5),
            line(&[(10.0, 4.5), (10.0, 2.5), (14.0, 2.5), (14.0, 4.5)]),
            rrect(9.3, 16.0, 14.7, 18.8, 0.4),
            rrect(9.3, 12.0, 14.7, 14.8, 0.4),
            line(&[(12.0, 6.5), (12.0, 10.0)]),
            line(&[(10.5, 8.0), (12.0, 6.5), (13.5, 8.0)]),
        ],
        ChargeStation => vec![
            rrect(4.0, 4.0, 14.0, 20.0, 1.5),
            bolt(9.0, 12.0, 8.0),
            line(&[(14.0, 8.0), (18.0, 8.0), (19.5, 10.0), (19.5, 15.5)]),
            rrect(18.0, 15.5, 21.0, 19.0, 0.8),
            line(&[(2.5, 20.0), (15.5, 20.0)]),
        ],
        ChargeNetwork => vec![
            circ(12.0, 11.5, 4.0),
            bolt(12.0, 11.5, 5.0),
            circ(4.5, 5.0, 2.0),
            circ(19.5, 5.0, 2.0),
            circ(12.0, 20.0, 2.0),
            line(&[(6.0, 6.3), (9.1, 8.8)]),
            line(&[(18.0, 6.3), (14.9, 8.8)]),
            line(&[(12.0, 18.0), (12.0, 15.5)]),
        ],
        ChargeSocket => vec![
            line(&[
                (6.0, 4.5),
                (18.0, 4.5),
                (20.0, 7.5),
                (20.5, 11.5),
                (19.0, 16.5),
                (15.5, 20.0),
                (12.0, 21.0),
                (8.5, 20.0),
                (5.0, 16.5),
                (3.5, 11.5),
                (4.0, 7.5),
                (6.0, 4.5),
            ]),
            circ(9.0, 8.5, 1.3),
            circ(15.0, 8.5, 1.3),
            circ(7.5, 13.0, 1.5),
            circ(12.0, 13.0, 1.5),
            circ(16.5, 13.0, 1.5),
            circ(9.5, 17.3, 1.3),
            circ(14.5, 17.3, 1.3),
        ],
        CarCharging => {
            let mut v = fit(body(HATCH), 0.7, 0.3, 6.4);
            v.push(bolt(18.5, 6.5, 8.0));
            v
        }
        Co2 => vec![
            arc(6.5, 12.0, 3.5, 40.0, 320.0),
            circ(13.5, 12.0, 3.5),
            line(&[
                (18.3, 15.4),
                (19.2, 14.4),
                (20.6, 14.4),
                (21.4, 15.2),
                (21.4, 16.0),
                (18.3, 19.2),
                (21.6, 19.2),
            ]),
        ],
        Co2Class => vec![
            poly(&[
                (3.0, 3.5),
                (11.0, 3.5),
                (12.5, 5.0),
                (11.0, 6.5),
                (3.0, 6.5),
            ]),
            poly(&[
                (3.0, 8.0),
                (14.0, 8.0),
                (15.5, 9.5),
                (14.0, 11.0),
                (3.0, 11.0),
            ]),
            poly(&[
                (3.0, 12.5),
                (17.0, 12.5),
                (18.5, 14.0),
                (17.0, 15.5),
                (3.0, 15.5),
            ]),
            poly(&[
                (3.0, 17.0),
                (20.0, 17.0),
                (21.5, 18.5),
                (20.0, 20.0),
                (3.0, 20.0),
            ]),
            poly(&[(17.5, 9.5), (21.5, 7.5), (21.5, 11.5)]),
        ],
        Exhaust => vec![
            rrect(2.0, 14.0, 11.0, 18.5, 1.0),
            line(&[(11.0, 15.0), (13.5, 14.0), (13.5, 18.5), (11.0, 17.5)]),
            curve(
                &[
                    (15.0, 13.5),
                    (15.5, 11.0),
                    (18.0, 10.5),
                    (18.5, 12.5),
                    (20.5, 12.0),
                ],
                false,
                6,
            ),
            curve(
                &[
                    (16.0, 8.0),
                    (16.5, 5.5),
                    (19.0, 5.0),
                    (19.5, 7.0),
                    (21.5, 6.5),
                ],
                false,
                6,
            ),
            line(&[(2.0, 21.0), (13.5, 21.0)]),
        ],
        ExhaustFluid => vec![
            super::drop(15.5, 9.5, 4.5),
            line(&[
                (12.5, 10.5),
                (14.0, 11.5),
                (15.5, 10.5),
                (17.0, 11.5),
                (18.5, 10.5),
            ]),
            rrect(2.0, 15.5, 11.0, 20.0, 1.0),
            line(&[(11.0, 16.5), (13.5, 15.5), (13.5, 20.0), (11.0, 19.0)]),
            line(&[(16.0, 17.75), (22.0, 17.75)]),
        ],
        Particulate => {
            let mut v = vec![
                rrect(5.0, 6.0, 19.0, 18.0, 2.0),
                line(&[(2.0, 12.0), (5.0, 12.0)]),
                line(&[(19.0, 12.0), (22.0, 12.0)]),
            ];
            for (x, y) in [
                (8.5, 9.5),
                (12.0, 9.5),
                (15.5, 9.5),
                (10.2, 12.0),
                (13.8, 12.0),
                (8.5, 14.5),
                (12.0, 14.5),
                (15.5, 14.5),
            ] {
                v.push(dot(x, y));
            }
            v
        }
        _ => Vec::new(),
    }
}
