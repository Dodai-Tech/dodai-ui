/// A star with `n` points.
fn star(cx: f32, cy: f32, ro: f32, ri: f32, n: usize) -> Shape {
    let pts = (0..n * 2)
        .map(|k| {
            let a = rad(-90.0 + 180.0 * k as f32 / n as f32);
            let r = if k % 2 == 0 { ro } else { ri };
            (cx + r * a.cos(), cy + r * a.sin())
        })
        .collect();
    (pts, true)
}

