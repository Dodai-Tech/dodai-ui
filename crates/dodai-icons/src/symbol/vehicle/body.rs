//! Body styles, roads and places around the car.

use super::*;

/// The open two-seater: a flat waist, a raked screen and nothing over the cabin.
fn open_top() -> Vec<Shape> {
    let mut v = body(&[
        (2.5, 16.5),
        (2.5, 12.8),
        (4.0, 12.0),
        (20.0, 12.0),
        (21.5, 13.5),
        (21.5, 16.5),
    ]);
    v.push(line(&[(14.5, 12.0), (12.5, 8.8)]));
    v
}

/// `v` with extra detail lines.
fn plus(mut v: Vec<Shape>, extra: Vec<Shape>) -> Vec<Shape> {
    v.extend(extra);
    v
}

