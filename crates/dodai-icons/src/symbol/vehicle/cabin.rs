/// A seat seen from the side, facing right, shifted by `dx`.
fn seat(dx: f32) -> Vec<Shape> {
    fit(
        vec![
            rrect(5.5, 2.5, 9.5, 5.5, 1.0),
            poly(&[(6.0, 7.0), (9.5, 7.0), (11.0, 14.0), (7.5, 15.5)]),
            rrect(8.0, 14.0, 19.0, 17.5, 1.5),
            line(&[(13.0, 17.5), (13.0, 21.0)]),
            line(&[(9.0, 21.0), (17.0, 21.0)]),
        ],
        1.0,
        dx,
        0.0,
    )
}

/// The plain three-spoke wheel of radius `r` around `(cx, cy)`.
fn wheel(cx: f32, cy: f32, r: f32) -> Vec<Shape> {
    let hub = r * 0.3;
    vec![
        circ(cx, cy, r),
        circ(cx, cy, hub),
        line(&[(cx - r, cy), (cx - hub, cy)]),
        line(&[(cx + hub, cy), (cx + r, cy)]),
        line(&[(cx, cy + hub), (cx, cy + r)]),
    ]
}

/// Three heat waves rising from `y`, centred on `cx`.
fn waves(cx: f32, y: f32) -> Vec<Shape> {
    [-3.0, 0.0, 3.0]
        .iter()
        .map(|dx| {
            let x = cx + dx;
            line(&[
                (x, y),
                (x - 0.8, y - 1.0),
                (x, y - 2.0),
                (x + 0.8, y - 3.0),
                (x, y - 4.0),
            ])
        })
        .collect()
}

