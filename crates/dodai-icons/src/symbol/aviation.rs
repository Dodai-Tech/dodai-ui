//! The aviation group: flight and airfield symbols.

use super::*;

/// A top-view airliner nose-up, centred at `(cx, cy)`, `s` tall.
fn jet(cx: f32, cy: f32, s: f32) -> Vec<Shape> {
    let k = s / 20.0;
    let p = |x: f32, y: f32| (cx + x * k, cy + y * k);
    vec![(
        vec![
            p(0.0, -10.0),
            p(1.5, -6.0),
            p(1.5, -2.0),
            p(10.0, 3.0),
            p(10.0, 5.0),
            p(1.5, 3.0),
            p(1.2, 7.5),
            p(4.5, 9.5),
            p(4.5, 10.5),
            p(0.0, 9.5),
            p(-4.5, 10.5),
            p(-4.5, 9.5),
            p(-1.2, 7.5),
            p(-1.5, 3.0),
            p(-10.0, 5.0),
            p(-10.0, 3.0),
            p(-1.5, -2.0),
            p(-1.5, -6.0),
        ],
        true,
    )]
}

