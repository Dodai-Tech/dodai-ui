/// A heart outline centred at `(cx, cy)`, `s` wide.
fn heart(cx: f32, cy: f32, s: f32) -> Shape {
    let r = s * 0.25;
    let mut pts = vec![(cx, cy + s * 0.5)];
    pts.extend(arc(cx - r, cy - r * 0.2, r, 150.0, 360.0).0);
    pts.extend(arc(cx + r, cy - r * 0.2, r, 180.0, 390.0).0);
    pts.push((cx, cy + s * 0.5));
    (pts, true)
}

