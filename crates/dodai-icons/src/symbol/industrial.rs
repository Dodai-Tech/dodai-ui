/// A cog with `n` teeth.
fn cog(cx: f32, cy: f32, ro: f32, ri: f32, n: usize) -> Shape {
    let mut pts = Vec::new();
    let step = 360.0 / n as f32;
    for k in 0..n {
        let a = -90.0 + step * k as f32;
        for (da, r) in [(-0.34, ri), (-0.2, ro), (0.2, ro), (0.34, ri)] {
            let t = rad(a + da * step);
            pts.push((cx + r * t.cos(), cy + r * t.sin()));
        }
    }
    (pts, true)
}

