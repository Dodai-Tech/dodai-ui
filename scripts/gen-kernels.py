#!/usr/bin/env python3
"""Regenerates, from the ShaderInfo tables in crates/dodai-shaders-kernels/src/shaders:
  * crates/dodai-shaders-kernels/src/entries.rs (one GPU entry point per shader)
  * crates/dodai-shaders/src/catalog.rs (the host-side catalogue: ids, names, families)"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "crates/dodai-shaders-kernels/src/shaders"
# catalogue order (families grouped); kernel entry order is separate and stable
cat_mods = "cyberpunk blade ghibli ghibli2 dmt pixel2 material matrix retro pixel nature fx extra retro2 ghostty".split()
mods = "cyberpunk blade ghibli ghibli2 dmt material matrix retro retro2 pixel pixel2 nature fx extra ghostty".split()
pat = re.compile(
    r'ShaderInfo::(generator|post)\(\s*"(\w+)",\s*"([^"]*)",\s*([\w:]+),\s*"([^"]*)",\s*(\w+),?\s*\)'
)
cpat = re.compile(r"const (\w+): Family = (Family::\w+);")
rows = {}
for m in set(mods + cat_mods):
    text = (src / f"{m}.rs").read_text()
    consts = dict(cpat.findall(text))
    rows[m] = [
        (k, i, n, consts.get(f, f), d, fn) for k, i, n, f, d, fn in pat.findall(text)
    ]
gens, posts = [], []
for m in mods:
    for k, i, n, f, d, fn in rows[m]:
        (gens if k == "generator" else posts).append((i, m, fn))
out = "// @generated by scripts/gen-kernels.py from the ShaderInfo tables. Do not edit.\n\n"
out += "".join(f"gen_kernel!({i}, {m}::{fn});\n" for i, m, fn in gens)
out += "".join(f"post_kernel!({i}, {m}::{fn});\n" for i, m, fn in posts)
(root / "crates/dodai-shaders-kernels/src/entries.rs").write_text(out)

cat = "// @generated by scripts/gen-kernels.py from the ShaderInfo tables. Do not edit.\n\n"
cat += "use crate::{Family, ShaderInfo};\n\npub(crate) const SHADERS: &[ShaderInfo] = &[\n"
for m in cat_mods:
    for k, i, n, f, d, fn in rows[m]:
        assert f.startswith("Family::"), (m, i, f)
        cat += f'    ShaderInfo::{k}("{i}", "{n}", {f}, "{d}"),\n'
cat += "];\n"
(root / "crates/dodai-shaders/src/catalog.rs").write_text(cat)
print(f"{len(gens)} generators, {len(posts)} post effects")
