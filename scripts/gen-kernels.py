#!/usr/bin/env python3
"""Regenerates crates/dodai-shaders-kernels/src/entries.rs from the ShaderInfo
tables in crates/dodai-shaders/src (one GPU entry point per shader)."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "crates/dodai-shaders/src"
mods = "cyberpunk blade ghibli material matrix retro retro2 pixel pixel2 nature fx extra ghostty".split()
pat = re.compile(
    r'ShaderInfo::(generator|post)\(\s*"(\w+)",\s*"[^"]*",\s*[\w:]+,\s*"[^"]*",\s*(\w+),?\s*\)'
)
gens, posts = [], []
for m in mods:
    for k, i, fn in pat.findall((src / f"{m}.rs").read_text()):
        (gens if k == "generator" else posts).append((i, m, fn))
out = "// @generated by scripts/gen-kernels.py from the ShaderInfo tables. Do not edit.\n\n"
out += "".join(f"gen_kernel!({i}, {m}::{fn});\n" for i, m, fn in gens)
out += "".join(f"post_kernel!({i}, {m}::{fn});\n" for i, m, fn in posts)
(root / "crates/dodai-shaders-kernels/src/entries.rs").write_text(out)
print(f"{len(gens)} generators, {len(posts)} post effects")
